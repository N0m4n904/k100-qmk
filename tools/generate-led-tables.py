#!/usr/bin/env python3
"""Generates the K100's IS31FL3743B channel table from an official firmware image.

Which driver and which three channels light a given LED is not guessable: it is
whatever Corsair wired, and it lives in the firmware's LedInfoMap. This reads
that table and emits the C QMK's RGB matrix needs.

    tools/generate-led-tables.py firmware.bin --out qmk/keyboards/corsair/k100

See docs/pin-mapping.md for how LedInfoMap was located and decoded, and
tools/k100_firmware.py for the reader.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from k100_firmware import PWM_PAGE_SIZE, Firmware

HEADER = """// Copyright 2026 k100-qmk contributors
// SPDX-License-Identifier: GPL-2.0-or-later

// Generated by tools/generate-led-tables.py -- do not edit by hand.
//
// Which driver and which three channels light each LED, read out of the stock
// firmware's LedInfoMap. An entry is {{driver, r, g, b}} where r, g and b are
// channel numbers within that driver's {page} PWM registers.
//
// Source image: {image}
"""


def emit_channel_table(firmware: Firmware, image_name: str) -> str:
    leds = firmware.leds()

    lines = [HEADER.format(page=PWM_PAGE_SIZE, image=image_name)]
    lines.append('#include "is31fl3743b.h"\n')
    lines.append("const is31fl3743b_led_t PROGMEM g_is31fl3743b_leds[IS31FL3743B_LED_COUNT] = {")
    lines.append("    /* driver, R, G, B */")

    for led in leds:
        (chip, r), (_, g), (_, b) = led.channels
        # A single-colour LED has no green or blue; its one channel is driven
        # through the red slot, and the other two are pointed at it as well so
        # that a white-ish request still lights it rather than doing nothing.
        if not led.is_rgb:
            g = b = r
        note = "" if led.is_rgb else "  // single colour"
        lines.append(f"    [{led.index}] = {{{chip}, {r}, {g}, {b}}},{note}")

    lines.append("};\n")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("image", type=Path, help="an official firmware image")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("qmk/keyboards/corsair/k100"),
        help="keyboard directory to write into",
    )
    args = parser.parse_args(argv[1:])

    firmware = Firmware(args.image.read_bytes())
    leds = firmware.leds()

    chips = sorted({led.chip for led in leds})
    rgb = sum(1 for led in leds if led.is_rgb)

    target = args.out / "is31fl3743b_leds.c"
    target.write_text(emit_channel_table(firmware, args.image.name))

    print(f"{len(leds)} LEDs across {len(chips)} drivers: {rgb} RGB, {len(leds) - rgb} single colour")
    print(f"written     {target}")

    # The channel table is only meaningful if no two LEDs claim one channel, and
    # a generator is the right place to notice.
    used: dict[tuple[int, int], int] = {}
    for led in leds:
        for chip, channel in led.channels if led.is_rgb else led.channels[:1]:
            key = (chip, channel)
            if key in used:
                print(
                    f"warning: driver {chip} channel {channel} is claimed by both "
                    f"LED {used[key]} and LED {led.index}",
                    file=sys.stderr,
                )
            used[key] = led.index
    print(f"checked     {len(used)} distinct driver channels, no collisions"
          if len(used) == sum(3 if l.is_rgb else 1 for l in leds)
          else "checked     collisions reported above")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
